// Generate the browser's wire types from the actual Go API structs.
package main

import (
	"fmt"
	"os"
	"reflect"
	"strings"

	"github.com/cursor/fleet-agent/mesh"
)

func ts(t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		return ts(t.Elem()) + " | null"
	}
	if t.Kind() == reflect.Struct && t.Name() != "" {
		return t.Name()
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64, reflect.Int32, reflect.Uint, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Interface:
		return "unknown"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string"
		}
		return "Array<" + ts(t.Elem()) + ">"
	case reflect.Map:
		return "Record<string, " + ts(t.Elem()) + ">"
	default:
		panic("unhandled wire type " + t.String())
	}
}
func main() {
	if len(os.Args) != 2 {
		panic("usage: contracts output.ts")
	}
	var b strings.Builder
	b.WriteString("// Generated by agent/cmd/contracts. Do not edit by hand.\nexport const MESH_PROTOCOL = 2 as const;\n")
	values := []any{mesh.Member{}, mesh.Command{}, mesh.SubmitRequest{}, mesh.Receipt{}, mesh.Installation{}, mesh.Result{}, mesh.CatalogItem{}, mesh.Observation{}, mesh.Hello{}, mesh.PeerState{}, mesh.JobResultView{}, mesh.JobView{}}
	for _, v := range values {
		t := reflect.TypeOf(v)
		fmt.Fprintf(&b, "\nexport interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			if f.PkgPath != "" {
				continue
			}
			tag := strings.Split(f.Tag.Get("json"), ",")
			if tag[0] == "" || tag[0] == "-" {
				continue
			}
			optional := ""
			for _, flag := range tag[1:] {
				if flag == "omitempty" {
					optional = "?"
				}
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", tag[0], optional, ts(f.Type))
		}
		b.WriteString("}\n")
	}
	if err := os.WriteFile(os.Args[1], []byte(b.String()), 0644); err != nil {
		panic(err)
	}
}
